# -*- coding: utf-8 -*-
"""
npa_status_check.py – механічний детектор статусу норми перед цитуванням.

ПРИЗНАЧЕННЯ. Закриває клас помилок «мертва норма процитована як чинна».
zakon.rada.gov.ua дисципліновано маркує долю кожного положення у фігурних
дужках {..}: неконституційність, виключення, втрату чинності, зупинення,
редакції. Людина (і модель) фрагментарним читанням ці примітки пропускає.
Скрипт – ні: він читає ВСЮ статтю і класифікує КОЖНУ примітку.

ВИКОРИСТАННЯ:
    python3 npa_status_check.py <файл_повного_тексту_акта.txt> "Стаття 26"
    python3 npa_status_check.py vp.txt all          # усі статті поспіль

Файл готується так (обов'язково ПОВНИЙ текст акта, не фрагмент):
    curl .../laws/show/<id>/print -> html; зняти теги; зберегти .txt

ВЕРДИКТИ:
    [СТОП]     критичний маркер – положення мертве або під загрозою:
               цитувати ЗАБОРОНЕНО до ручного розбору примітки
    [УВАГА]    некритичний маркер (редакція, зміни) – звірити дату
               останньої зміни і чинну редакцію
    [ЧИСТО]    приміток немає – норма без застережень у тексті акта
               (це НЕ звільняє від перевірки спецрежимів: воєнний стан,
               карантин, перехідні положення інших законів)

ЖОРСТКЕ ПРАВИЛО: жодна стаття не йде в документ без прогону через цей
скрипт. Вердикт [СТОП] = зупинка і ручний розбір. Обрізати статтю
до фрагмента навколо ключового слова – заборонено.
"""
import re
import sys

CRIT = [
    (r'визнан[оі][^{}]{0,200}неконституційн', 'НЕКОНСТИТУЦІЙНІСТЬ (рішення КСУ)'),
    (r'Рішенням Конституційного Суду', 'згадка рішення КСУ'),
    (r'втрача[єю]ть чинність|втратив чинність|втратила чинність',
     'ВТРАТА ЧИННОСТІ'),
    (r'виключено на підставі|статтю\s+\d+[^{}]{0,80}виключено|частину[^{}]{0,80}виключено|пункт[^{}]{0,80}виключено|абзац[^{}]{0,80}виключено',
     'ВИКЛЮЧЕННЯ положення'),
    (r'зупин[еи]но[^{}]{0,120}(дію|чинність)|дію[^{}]{0,120}зупинено', 'ЗУПИНЕННЯ дії'),
    (r'не застосовується', 'НЕЗАСТОСУВАННЯ (обмеження дії)'),
    (r'на період[^{}]{0,120}(воєнного стану|карантину)', 'СПЕЦРЕЖИМ (війна/карантин)'),
]
WARN = [
    (r'в редакції Закону', 'нова редакція – звірити дату'),
    (r'із змінами, внесеними', 'зміни – звірити дату останньої'),
    (r'доповнено', 'доповнення'),
    (r'[Щщ]одо (введення в дію|доповнення|перенумерації)', 'перехідне застереження'),
    (r'[Дд]ив\. (Закон|пункт)', 'відсилання до перехідних положень'),
]


def split_article(text, art_no):
    m = re.search(r'\nСтаття\s+%s\.' % re.escape(art_no), '\n' + text)
    if not m:
        return None
    start = m.start()
    m2 = re.search(r'\nСтаття\s+[\d\-]+[\.\u00b9\u00b2\u00b3]', text[start + 12:])
    end = start + 12 + (m2.start() if m2 else len(text))
    return text[start:end]


def check(seg, label):
    notes = re.findall(r'\{[^{}]+\}', seg)
    # zakon.rada після зняття тегів лишає {} з переносами
    if not notes:
        notes = re.findall(r'\{[^}]+\}', seg.replace('\n', ' '))
    crit_hits, warn_hits = [], []
    flat = seg.replace('\n', ' ')
    for note in re.findall(r'\{[^}]+\}', flat):
        matched = False
        for pat, name in CRIT:
            if re.search(pat, note):
                crit_hits.append((name, note.strip()[:220]))
                matched = True
                break
        if not matched:
            for pat, name in WARN:
                if re.search(pat, note):
                    warn_hits.append((name, note.strip()[:160]))
                    break
    print('=' * 74)
    print('НОРМА:', label, '| приміток {} у тексті:', len(re.findall(r'\{[^}]+\}', flat)))
    if crit_hits:
        print('ВЕРДИКТ: [СТОП] – критичних маркерів:', len(crit_hits))
        for name, note in crit_hits:
            print('  !!', name)
            print('     ', note)
        print('  ЦИТУВАТИ ЗАБОРОНЕНО до ручного розбору кожної примітки вище.')
    elif warn_hits:
        print('ВЕРДИКТ: [УВАГА] – редакційних маркерів:', len(warn_hits))
        for name, note in warn_hits[:6]:
            print('  ~', name, '|', note)
        print('  Звірити дату останньої зміни; текст норми читати повністю.')
    else:
        print('ВЕРДИКТ: [ЧИСТО] – приміток немає.')
        print('  Окремо перевірити спецрежими поза текстом статті '
              '(перехідні положення, воєнний стан).')
    return bool(crit_hits)


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        sys.exit(1)
    text = open(sys.argv[1], encoding='utf-8').read()
    target = sys.argv[2]
    if target == 'all':
        arts = sorted(set(re.findall(r'\nСтаття\s+([\d\-]+)\.', '\n' + text)),
                      key=lambda x: [int(p) for p in x.split('-')])
        stops = 0
        for a in arts:
            seg = split_article(text, a)
            if seg and check(seg, 'Стаття ' + a):
                stops += 1
        print('\nРАЗОМ [СТОП]:', stops, 'з', len(arts))
    else:
        art_no = target.replace('Стаття', '').strip().rstrip('.')
        seg = split_article(text, art_no)
        if not seg:
            print('Статтю не знайдено:', target)
            sys.exit(2)
        check(seg, 'Стаття ' + art_no)


if __name__ == '__main__':
    main()
